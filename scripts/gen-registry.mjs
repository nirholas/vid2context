#!/usr/bin/env node
/**
 * Generates packages/registry/src/generated/{node,workers,browser}.ts from the
 * provider packages under providers/*. A provider package opts in with:
 *
 *   "vid2context": { "runtimes": ["node", "workers", "browser"] }
 *
 * in its package.json, and default-exports a Provider or Provider[] from its
 * entry point. Runs on postinstall and before typecheck/test, so adding a
 * provider never means editing a shared file. Output is sorted, so concurrent
 * runs always produce the same files.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const providersDir = join(root, 'providers');
const outDir = join(root, 'packages/registry/src/generated');
const RUNTIMES = ['node', 'workers', 'browser'];

const found = [];
for (const dir of existsSync(providersDir) ? readdirSync(providersDir).sort() : []) {
  const pkgPath = join(providersDir, dir, 'package.json');
  if (!existsSync(pkgPath)) continue;
  let pkg;
  try {
    pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  } catch (err) {
    console.error(`[gen-registry] skipping providers/${dir}: invalid package.json (${err.message})`);
    continue;
  }
  const runtimes = pkg.vid2context?.runtimes;
  if (!Array.isArray(runtimes) || runtimes.length === 0) continue;
  const bad = runtimes.filter((r) => !RUNTIMES.includes(r));
  if (bad.length) {
    console.error(`[gen-registry] providers/${dir}: unknown runtimes ${bad.join(', ')}`);
    continue;
  }
  found.push({ name: pkg.name, runtimes });
}

mkdirSync(outDir, { recursive: true });
for (const runtime of RUNTIMES) {
  const pkgs = found.filter((p) => p.runtimes.includes(runtime));
  const lines = [
    '// Generated by scripts/gen-registry.mjs. Do not edit; add a provider package under providers/ instead.',
    "import type { Provider } from '@vid2context/core';",
    ...pkgs.map((p, i) => `import p${i} from '${p.name}';`),
    '',
    'const list: (Provider | Provider[])[] = [' + pkgs.map((_, i) => `p${i}`).join(', ') + '];',
    'export const providers: Provider[] = list.flat();',
    `export const providerPackages: string[] = ${JSON.stringify(pkgs.map((p) => p.name))};`,
    '',
  ];
  writeFileSync(join(outDir, `${runtime}.ts`), lines.join('\n'));
}
console.error(`[gen-registry] ${found.length} provider package(s): ${found.map((p) => p.name).join(', ') || 'none'}`);
