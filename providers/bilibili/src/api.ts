// ---------------------------------------------------------------- per-ctx caches

/**
 * One response per URL per Ctx: the pipeline calls getMetadata, getCaptions
 * and getAudio with the same ctx, so the view call is shared; a new request
 * or CLI run always sees fresh data.
 */
const perCtx = new WeakMap<Ctx, Map<string, Promise<unknown>>>();

function cached<T>(ctx: Ctx, key: string, load: () => Promise<T>): Promise<T> {
  let cache = perCtx.get(ctx);
  if (!cache) {
    cache = new Map();
    perCtx.set(ctx, cache);
  }
  let pending = cache.get(key) as Promise<T> | undefined;
  if (!pending) {
    pending = load();
    cache.set(key, pending);
    pending.catch(() => cache.delete(key));
  }
  return pending;
}

export function getView(ctx: Ctx, bvid: string): Promise<ViewData> {
  return cached(ctx, `view:${bvid}`, () => apiGet<ViewData>(ctx, `/x/web-interface/view?bvid=${bvid}`, `video ${bvid}`));
}

export function getTags(ctx: Ctx, bvid: string): Promise<{ tag_name: string }[]> {
  return cached(ctx, `tags:${bvid}`, () =>
    apiGet<{ tag_name: string }[]>(ctx, `/x/tag/archive/tags?bvid=${bvid}`, `tags ${bvid}`),
  );
}

export function getSubtitleList(ctx: Ctx, aid: number, cid: number): Promise<{ subtitle?: SubtitleList }> {
  return cached(ctx, `dm:${cid}`, () =>
    apiGet<{ subtitle?: SubtitleList }>(ctx, `/x/v2/dm/view?type=1&oid=${cid}&pid=${aid}`, `subtitles for cid ${cid}`),
  );
}

export function getWbiKey(ctx: Ctx): Promise<string> {
  return cached(ctx, 'wbi', async () => {
    const res = await fetchWithTimeout(ctx, `${API}/x/web-interface/nav`, { headers: biliHeaders(ctx) });
    if (!res.ok) throw new Vid2ContextError('upstream', `Bilibili nav: HTTP ${res.status}`, { status: res.status });
    // nav answers code -101 when logged out, but still carries the WBI keys.
    const body = (await res.json()) as Envelope<{ wbi_img?: { img_url?: string; sub_url?: string } }>;
    const img = body.data?.wbi_img;
    if (!img?.img_url || !img.sub_url) throw new Vid2ContextError('upstream', 'Bilibili nav returned no WBI keys.');
    return mixinKey(img.img_url, img.sub_url);
  });
}

async function signedPath(ctx: Ctx, path: string, params: Record<string, string | number>): Promise<string> {
  return `${path}?${signQuery(params, await getWbiKey(ctx))}`;
}

export function getPlayer(ctx: Ctx, bvid: string, cid: number): Promise<PlayerData> {
  return cached(ctx, `player:${cid}`, async () =>
    apiGet<PlayerData>(ctx, await signedPath(ctx, '/x/player/wbi/v2', { bvid, cid }), `player info ${bvid}`),
  );
}

export function getPlayurl(ctx: Ctx, bvid: string, cid: number): Promise<PlayurlData> {
  // fnval 16 asks for DASH, which lists audio separately from video.
  return cached(ctx, `playurl:${cid}`, async () =>
    apiGet<PlayurlData>(ctx, await signedPath(ctx, '/x/player/wbi/playurl', { bvid, cid, fnval: 16 }), `play URLs ${bvid}`),
  );
}

// ---------------------------------------------------------------- refs to concrete parts

/** Follow a b23.tv short link with one HEAD request (no body, no redirect following). */
export function resolveShort(ctx: Ctx, code: string): Promise<BiliTarget> {
  return cached(ctx, `b23:${code}`, async () => {
    const res = await fetchWithTimeout(ctx, `https://b23.tv/${code}`, {
      method: 'HEAD',
      redirect: 'manual',
      headers: { 'user-agent': USER_AGENT },
    });
    const location = res.headers.get('location') ?? (res.url && !res.url.includes('b23.tv') ? res.url : '');
    const target = location ? /\/video\/((?:BV|av)[A-Za-z0-9]+)/i.exec(location) : null;
    const bvid = target?.[1] ? toBvid(target[1]) : null;
    if (!bvid) {
      throw new Vid2ContextError('not-found', `b23.tv/${code} does not lead to a Bilibili video.`, {
        hint: 'Open the short link in a browser and pass the bilibili.com/video/BV... URL it lands on.',
      });
    }
    const p = location ? new URL(location, 'https://www.bilibili.com').searchParams.get('p') : null;
    return { bvid, page: p && /^\d+$/.test(p) ? Number(p) : 1 };
  });
}

export interface Part {
  bvid: string;
  /** 1-based. */
  page: number;
  view: ViewData;
  cid: number;
  pageInfo?: ViewPage;
}

/** The BV id, view data and part (cid) a video ref points at. */
export async function resolvePart(ref: VideoRef, ctx: Ctx): Promise<Part> {
  const parsed = parseRef(ref);
  if (!parsed) throw new Vid2ContextError('bad-request', `Not a Bilibili ref: ${ref.id}`);
  const target = 'short' in parsed ? await resolveShort(ctx, parsed.short) : parsed;
  const page = target.page === 'all' ? 1 : target.page;
  const view = await getView(ctx, target.bvid);
  const pages = view.pages ?? [];
  const pageInfo = pages.find((p) => p.page === page) ?? (page === 1 ? undefined : null);
  if (pageInfo === null) {
    throw new Vid2ContextError('not-found', `${target.bvid} has ${pages.length} part(s); there is no part ${page}.`, {
      hint: `Use ?p=1 to ?p=${pages.length}, or ?p=all to list every part.`,
    });
  }
  return { bvid: target.bvid, page, view, cid: pageInfo?.cid ?? view.cid, pageInfo };
}
