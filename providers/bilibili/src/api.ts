/**
 * Bilibili web API client. Every call goes through ctx.fetch with a browser
 * User-Agent and the www.bilibili.com Referer the site's own player sends;
 * BILIBILI_SESSDATA (optional) is sent as the SESSDATA cookie. Endpoints and
 * the WBI signature follow yt-dlp's bilibili extractor (Unlicense).
 *
 *   /x/web-interface/view             video info, parts (pages), owner, cover    unsigned
 *   /x/tag/archive/tags               tags                                       unsigned
 *   /x/v2/dm/view                     subtitle list with fetchable URLs           unsigned
 *   /x/player/wbi/v2                  chapters (view_points); subtitles when signed in   WBI
 *   /x/player/wbi/playurl             DASH audio stream URLs                      WBI
 *   /x/web-interface/nav              WBI keys                                    unsigned
 */
import { type Ctx, fetchWithTimeout, Vid2ContextError, type VideoRef } from '@vid2context/core';
import { type BiliTarget, parseRef, toBvid } from './url.ts';
import { mixinKey, signQuery } from './wbi.ts';

export const API = 'https://api.bilibili.com';
export const REFERER = 'https://www.bilibili.com/';
export const USER_AGENT =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

export const BLOCKED_HINT =
  'Bilibili is rejecting requests from this IP address (risk control). Wait a few minutes, run vid2context from another network, ' +
  'or set BILIBILI_SESSDATA to a logged-in session cookie.';

export function biliHeaders(ctx: Ctx, extra: Record<string, string> = {}): Record<string, string> {
  const headers: Record<string, string> = { 'user-agent': USER_AGENT, referer: REFERER, ...extra };
  const sessdata = ctx.env.BILIBILI_SESSDATA?.trim();
  if (sessdata) headers.cookie = `SESSDATA=${sessdata}`;
  return headers;
}

interface Envelope<T> {
  code: number;
  message?: string;
  data?: T;
}

/** Map a Bilibili API error code to a Vid2ContextError. */
export function apiError(code: number, message: string, what: string): Vid2ContextError {
  const msg = `Bilibili ${what}: ${code}${message ? ` ${message}` : ''}`;
  switch (code) {
    case -404:
    case 62004:
      return code === -404
        ? new Vid2ContextError('not-found', msg, { hint: 'Check the BV id or URL; the video may have been deleted.' })
        : new Vid2ContextError('unavailable', msg, { hint: 'The video is still under review. Try again later.' });
    case 62002:
    case 62012:
    case -403:
    case 87008:
      return new Vid2ContextError('unavailable', msg, {
        hint: 'The video is hidden, private to its uploader, or for paying members only.',
      });
    case -10403:
    case 6002003:
      return new Vid2ContextError('unavailable', msg, {
        hint: 'The video is not available in the region this request came from.',
      });
    case -412:
    case -352:
      return new Vid2ContextError('blocked', msg, { hint: BLOCKED_HINT });
    case -101:
      return new Vid2ContextError('auth', msg, { hint: 'This needs a logged-in session: set BILIBILI_SESSDATA.' });
    case -400:
      return new Vid2ContextError('bad-request', msg);
    default:
      return new Vid2ContextError('upstream', msg);
  }
}

export async function apiGet<T>(ctx: Ctx, path: string, what: string): Promise<T> {
  const res = await fetchWithTimeout(ctx, `${API}${path}`, { headers: biliHeaders(ctx) });
  if (res.status === 412)
    throw new Vid2ContextError('blocked', `Bilibili ${what}: HTTP 412`, { status: 412, hint: BLOCKED_HINT });
  if (!res.ok) {
    const code = res.status === 404 ? 'not-found' : res.status === 429 ? 'rate-limited' : 'upstream';
    throw new Vid2ContextError(code, `Bilibili ${what}: HTTP ${res.status}`, { status: res.status });
  }
  const body = (await res.json()) as Envelope<T>;
  if (body.code !== 0 || body.data === undefined) throw apiError(body.code, body.message ?? '', what);
  return body.data;
}

