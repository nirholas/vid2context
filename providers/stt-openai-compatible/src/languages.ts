/** "english" -> "en", "en" -> "en", "pt-BR" -> "pt-BR"; undefined when empty. */
export function normalizeLanguage(value: string | undefined): string | undefined {
  const v = value?.trim();
  if (!v) return undefined;
  if (/^[a-z]{2,3}([-_][A-Za-z0-9]+)*$/i.test(v) && !(v.toLowerCase() in BY_NAME)) return v;
  return BY_NAME[v.toLowerCase()] ?? v;
}
