#!/usr/bin/env node
/**
 * Embeds migrations/*.sql into src/migrations.generated.ts so the storage can
 * apply them on runtimes without a filesystem (Cloudflare Workers). The SQL
 * files stay the source of truth; test/migrations.test.ts fails when the
 * generated module is out of date. Run: node scripts/embed-migrations.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function renderMigrationsModule(dir) {
  const files = readdirSync(dir)
    .filter((f) => /^\d{4}_[a-z0-9_]+\.sql$/.test(f))
    .sort();
  const entries = files.map((file) => {
    const version = Number(file.slice(0, 4));
    const name = file.slice(5, -4);
    const sql = readFileSync(join(dir, file), 'utf8');
    return `  { version: ${version}, name: ${JSON.stringify(name)}, sql: ${JSON.stringify(sql)} },`;
  });
  return [
    '// Generated by scripts/embed-migrations.mjs from migrations/*.sql. Do not edit; change the SQL files and rerun the script.',
    '',
    'export interface Migration {',
    '  version: number;',
    '  name: string;',
    '  sql: string;',
    '}',
    '',
    'export const migrations: Migration[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, 'src/migrations.generated.ts'), renderMigrationsModule(join(root, 'migrations')));
  console.error('[embed-migrations] wrote src/migrations.generated.ts');
}
