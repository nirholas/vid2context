/**
 * Supadata captions: YouTube transcripts through the Supadata transcript API,
 * which fetches from its own IP pool. A fallback for when YouTube blocks
 * caption downloads from this machine's IP (cloud VMs get HTTP 429 on timedtext).
 *
 * - Enabled only when SUPADATA_API_KEY is set (free plan: 100 credits a month,
 *   1 request a second, from https://supadata.ai/pricing on 2026-11-14).
 * - order 100: runs after youtube-captions and ytdlp-captions (order 0), so the
 *   monthly credits are spent only when the keyless providers found nothing.
 * - mode=native only: Supadata's AI generation is never used (our own
 *   speech-to-text rungs do that job).
 *
 * Origin: Supadata does not say whether a track was uploaded by the creator or
 * generated by YouTube (no such field in the TranscriptChunk or response schema
 * of https://docs.supadata.ai/api-reference/endpoint/transcript/transcript,
 * 2026-11-14). The honest label is the less trusted one, 'auto-captions', and
 * when the caller disallows auto-captions this provider returns null.
 *
 * Env: SUPADATA_API_KEY, SUPADATA_BASE_URL, SUPADATA_MAX_WAIT_SEC.
 * The key is sent only in the x-api-key header and is never logged.
 */
import { type CaptionsProvider, defineProvider, type Env, type Transcript, Vid2ContextError } from '@vid2context/core';
import { fetchTranscript, settings, toSegments } from './api.ts';

export * from './api.ts';

export const SUPADATA_ORDER = 100;

function primary(lang: string): string {
  return lang.toLowerCase().split(/[-_]/)[0] ?? '';
}

export const supadataCaptions: CaptionsProvider = defineProvider({
  id: 'supadata-captions',
  kind: 'captions',
  name: 'Supadata YouTube captions',
  runtimes: ['node', 'workers'],
  order: SUPADATA_ORDER,
  isEnabled: (env: Env) => Boolean(settings(env).key),
  requires: ['SUPADATA_API_KEY'],
  supports: (ref) => ref.platform === 'youtube' && ref.kind === 'video',
  async getCaptions(ref, opts, ctx): Promise<Transcript | null> {
    // The pipeline does not filter by isEnabled yet, so check the key here too.
    if (!settings(ctx.env).key) return null;
    if (opts.allowAuto === false) {
      ctx.log.debug('supadata-captions: skipped, Supadata cannot tell creator captions from auto-captions', {
        videoId: ref.nativeId,
      });
      return null;
    }
    const result = await fetchTranscript(ref.nativeId, opts.language, ctx);
    if (!result) return null;
    const { transcript } = result;
    const chunks = Array.isArray(transcript.content) ? transcript.content : [];
    const language = transcript.lang || chunks[0]?.lang || opts.language || 'und';
    // [T] "If the video does not have a transcript in the preferred language, the endpoint
    // will return a transcript in the first available language". Not what was asked for.
    if (opts.language && primary(language) !== primary(opts.language)) {
      ctx.log.debug('supadata-captions: requested language not available', {
        videoId: ref.nativeId,
        requested: opts.language,
        returned: language,
        available: transcript.availableLangs,
      });
      return null;
    }
    const segments = toSegments(chunks);
    if (segments.length === 0 && chunks.length > 0) {
      throw new Vid2ContextError('upstream', `Supadata: ${chunks.length} transcript chunks, none with text and a start time.`);
    }
    if (segments.length === 0) return null;
    return {
      ref,
      language,
      origin: 'auto-captions',
      producer: 'supadata-captions',
      segments,
      createdAt: new Date().toISOString(),
    };
  },
});

export default supadataCaptions;
