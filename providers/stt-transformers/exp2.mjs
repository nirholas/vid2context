import { spawnSync } from 'node:child_process';
import { pipeline, env } from '@huggingface/transformers';
env.cacheDir = process.argv[2];
const [model, dtype, extra] = process.argv.slice(3);
const r = spawnSync('ffmpeg', ['-hide_banner','-loglevel','error','-stream_loop','2','-i', '../../tests/fixtures/media/apollo11-small-step.mp3', '-f','f32le','-ac','1','-ar','16000','-'], { maxBuffer: 1<<30 });
const audio = new Float32Array(r.stdout.buffer, r.stdout.byteOffset, r.stdout.byteLength/4);
const pipe = await pipeline('automatic-speech-recognition', model, { device: 'cpu', dtype });
const t = Date.now();
const out = await pipe(audio, { return_timestamps: true, chunk_length_s: 30, stride_length_s: 5, language: 'en', task: 'transcribe', ...JSON.parse(extra||'{}') });
console.log(model, dtype, extra, Date.now()-t, 'ms');
for (const c of out.chunks) console.log(JSON.stringify(c.timestamp), c.text.slice(0, 90));
