#!/usr/bin/env node
/**
 * Embeds src/templates/*.md (the template prompt text) into
 * src/templates/prompts.generated.ts so the package runs on runtimes without
 * a filesystem or a Markdown loader (Cloudflare Workers, browsers, plain
 * tsx). The .md files are the source of truth; test/templates.test.ts fails
 * when the generated module is out of date. Run: node scripts/embed-templates.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function renderTemplatePromptsModule(dir) {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .sort();
  const entries = files.map((file) => {
    const id = file.slice(0, -3);
    const text = readFileSync(join(dir, file), 'utf8').trimEnd();
    return `  ${JSON.stringify(id)}: ${JSON.stringify(text)},`;
  });
  return [
    '// Generated by scripts/embed-templates.mjs from src/templates/*.md. Do not edit; change the Markdown files and rerun the script.',
    '',
    '/** Template prompt text by template id, from src/templates/<id>.md with trailing whitespace trimmed. */',
    'export const templatePrompts: Record<string, string> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, 'src/templates/prompts.generated.ts'), renderTemplatePromptsModule(join(root, 'src/templates')));
  console.error('[embed-templates] wrote src/templates/prompts.generated.ts');
}
