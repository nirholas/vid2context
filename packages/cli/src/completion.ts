/**
 * Shell completion scripts, generated from the command table in spec.ts so
 * they always match `--help`.
 */
import { COMMANDS, type CommandSpec, FLAGS, type FlagSpec, flagsFor, GLOBAL_FLAGS } from './spec.ts';

/** Flags whose value completes as a file path. */
const FILE_FLAGS = new Set(['out']);
/** String flags whose value is optional, so completion treats them like booleans. */
const OPTIONAL_VALUE = new Set(['comments']);

function takesValue(f: FlagSpec): boolean {
  return f.type === 'string' && !OPTIONAL_VALUE.has(f.name);
}

function globals(): FlagSpec[] {
  return GLOBAL_FLAGS.map((n) => FLAGS[n]).filter((f): f is FlagSpec => Boolean(f));
}

function flagWords(flags: FlagSpec[]): string {
  return flags.flatMap((f) => [`--${f.name}`, ...(f.short ? [`-${f.short}`] : [])]).join(' ');
}

// ---------------------------------------------------------------- bash

export function bashCompletion(): string {
  const names = COMMANDS.map((c) => c.name);
  const valueFlags = Object.values(FLAGS).filter(takesValue);
  const valueCases = valueFlags
    .map((f) => {
      const pat = [`--${f.name}`, ...(f.short ? [`-${f.short}`] : [])].join('|');
      if (f.choices) return `    ${pat}) COMPREPLY=($(compgen -W "${f.choices().join(' ')}" -- "$cur")); return ;;`;
      if (FILE_FLAGS.has(f.name)) return `    ${pat}) COMPREPLY=($(compgen -f -- "$cur")); return ;;`;
      return `    ${pat}) return ;;`;
    })
    .join('\n');
  const flagCases = COMMANDS.map((c) => `    ${c.name}) flags="${flagWords(flagsFor(c))}" ;;`).join('\n');
  const argCases = COMMANDS.filter((c) => c.subcommands || c.name === 'completion' || c.name === 'help' || c.completesFiles)
    .map((c) => {
      if (c.subcommands) {
        return `    ${c.name}) [[ "$prev" == "${c.name}" ]] && COMPREPLY=($(compgen -W "${c.subcommands.map((s) => s.name).join(' ')}" -- "$cur")) ;;`;
      }
      if (c.name === 'completion') return `    completion) COMPREPLY=($(compgen -W "bash zsh fish" -- "$cur")) ;;`;
      if (c.name === 'help') return `    help) COMPREPLY=($(compgen -W "${names.join(' ')}" -- "$cur")) ;;`;
      return `    ${c.name}) COMPREPLY=($(compgen -f -- "$cur")) ;;`;
    })
    .join('\n');
  return `# bash completion for vid2context. Generated by \`vid2context completion bash\`.
_vid2context() {
  local cur prev cmd i flags
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"
  cmd=""
  for ((i = 1; i < COMP_CWORD; i++)); do
    case "\${COMP_WORDS[i]}" in
      ${names.join('|')}) cmd="\${COMP_WORDS[i]}"; break ;;
    esac
  done
  case "$prev" in
${valueCases}
  esac
  case "$cmd" in
${flagCases}
    *) flags="${flagWords(globals())}" ;;
  esac
  if [[ "$cur" == -* ]]; then
    COMPREPLY=($(compgen -W "$flags" -- "$cur"))
    return
  fi
  case "$cmd" in
    "") COMPREPLY=($(compgen -W "${names.join(' ')}" -- "$cur") $(compgen -f -- "$cur")) ;;
${argCases}
  esac
}
complete -o default -F _vid2context vid2context
`;
}

// ---------------------------------------------------------------- zsh

function zshText(s: string): string {
  return s.replace(/[[\]:'\\`$]/g, '').replace(/\|/g, 'or');
}

function zshFlag(f: FlagSpec): string[] {
  const desc = zshText(f.description);
  let value = '';
  if (takesValue(f)) {
    if (f.choices) value = `:${f.name}:(${f.choices().join(' ')})`;
    else if (FILE_FLAGS.has(f.name)) value = `:file:_files`;
    else value = `:${f.name}: `;
  }
  const star = f.multiple ? '*' : '';
  return [`'${star}--${f.name}[${desc}]${value}'`, ...(f.short ? [`'${star}-${f.short}[${desc}]${value}'`] : [])];
}

function zshArgs(c: CommandSpec): string {
  const specs = flagsFor(c).flatMap(zshFlag);
  if (c.subcommands) specs.push(`'1:subcommand:(${c.subcommands.map((s) => s.name).join(' ')})'`, `'*:argument: '`);
  else if (c.name === 'completion') specs.push(`'1:shell:(bash zsh fish)'`);
  else if (c.name === 'help') specs.push(`'1:command:(${COMMANDS.map((x) => x.name).join(' ')})'`);
  else if (c.completesFiles) specs.push(`'*:input:_files'`);
  else if (c.args) specs.push(`'*:argument: '`);
  return specs.join(' \\\n        ');
}

export function zshCompletion(): string {
  const commands = COMMANDS.map((c) => `    '${c.name}:${zshText(c.summary)}'`).join('\n');
  const cases = COMMANDS.map((c) => `    ${c.name})\n      _arguments -s \\\n        ${zshArgs(c)}\n      ;;`).join('\n');
  const globalSpecs = globals().flatMap(zshFlag).join(' \\\n        ');
  return `#compdef vid2context
# zsh completion for vid2context. Generated by \`vid2context completion zsh\`.
_vid2context() {
  local -a commands
  commands=(
${commands}
  )
  if (( CURRENT == 2 )); then
    _describe -t commands 'vid2context command' commands
    _files
    return
  fi
  local cmd=\${words[2]}
  shift words
  (( CURRENT-- ))
  case $cmd in
${cases}
    *)
      _arguments -s \\
        ${globalSpecs} \\
        '*:input:_files'
      ;;
  esac
}
compdef _vid2context vid2context
`;
}

// ---------------------------------------------------------------- fish

function fishText(s: string): string {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function fishFlag(f: FlagSpec, condition?: string): string {
  const parts = ['complete -c vid2context'];
  if (condition) parts.push(`-n '${condition}'`);
  parts.push(`-l ${f.name}`);
  if (f.short) parts.push(`-s ${f.short}`);
  if (takesValue(f)) {
    if (f.choices) parts.push(`-x -a '${f.choices().join(' ')}'`);
    else if (FILE_FLAGS.has(f.name)) parts.push('-r -F');
    else parts.push('-x');
  }
  parts.push(`-d '${fishText(f.description)}'`);
  return parts.join(' ');
}

export function fishCompletion(): string {
  const names = COMMANDS.map((c) => c.name).join(' ');
  const lines = [
    '# fish completion for vid2context. Generated by `vid2context completion fish`.',
    'complete -c vid2context -f',
    ...COMMANDS.map(
      (c) => `complete -c vid2context -n 'not __fish_seen_subcommand_from ${names}' -a ${c.name} -d '${fishText(c.summary)}'`,
    ),
    `complete -c vid2context -n 'not __fish_seen_subcommand_from ${names}' -F`,
    ...globals().map((f) => fishFlag(f)),
  ];
  for (const c of COMMANDS) {
    const cond = `__fish_seen_subcommand_from ${c.name}`;
    for (const n of c.flags) {
      const f = FLAGS[n];
      if (f) lines.push(fishFlag(f, cond));
    }
    if (c.subcommands) {
      const subs = c.subcommands.map((s) => s.name).join(' ');
      for (const s of c.subcommands) {
        lines.push(`complete -c vid2context -n '${cond}; and not __fish_seen_subcommand_from ${subs}' -a ${s.name} -d '${fishText(s.summary)}'`);
      }
    }
    if (c.name === 'completion') lines.push(`complete -c vid2context -n '${cond}' -a 'bash zsh fish'`);
    if (c.name === 'help') lines.push(`complete -c vid2context -n '${cond}' -a '${names}'`);
    if (c.completesFiles) lines.push(`complete -c vid2context -n '${cond}' -F`);
  }
  return `${lines.join('\n')}\n`;
}

export function completionScript(shell: 'bash' | 'zsh' | 'fish'): string {
  return shell === 'bash' ? bashCompletion() : shell === 'zsh' ? zshCompletion() : fishCompletion();
}
