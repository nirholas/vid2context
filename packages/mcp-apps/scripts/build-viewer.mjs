/**
 * Bundles the transcript viewer (src/ui/) into one self-contained HTML
 * document and writes it to src/ui/viewer.html.ts as a string constant, so
 * the package keeps exporting TypeScript source with no build step.
 *
 * Everything is inlined (CSS and JS): MCP Apps hosts sandbox the viewer with
 * a CSP that allows no external scripts, styles, fonts or images.
 *
 *   node packages/mcp-apps/scripts/build-viewer.mjs          write the file
 *   node packages/mcp-apps/scripts/build-viewer.mjs --check  exit 1 when the committed file is stale
 *
 * test/bundle.test.ts rebuilds it and fails when the committed output differs.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, transform } from 'esbuild';

// Paths, not URLs: test DOM environments replace the global URL class.
const here = import.meta.dirname ?? dirname(fileURLToPath(import.meta.url));
const uiDir = join(here, '..', 'src', 'ui');
export const outFile = join(uiDir, 'viewer.html.ts');

/** Build the viewer and return the full contents of src/ui/viewer.html.ts. */
export async function buildViewerSource() {
  const js = await build({
    entryPoints: [join(uiDir, 'main.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    // ASCII output: library strings with non-ASCII characters become \u escapes.
    charset: 'ascii',
    logLevel: 'silent',
  });
  const script = js.outputFiles[0].text.trim();
  const css = await transform(readFileSync(join(uiDir, 'styles.css'), 'utf8'), {
    loader: 'css',
    minify: true,
    target: 'chrome110',
  });
  // "</" inside an inline script or style would end the element early.
  const safeScript = script.replace(/<\/(script)/gi, '<\\/$1');
  const safeCss = css.code.trim().replace(/<\/(style)/gi, '<\\/$1');
  const html =
    '<!doctype html><html lang="en" data-theme="system"><head><meta charset="utf-8">' +
    '<meta name="viewport" content="width=device-width, initial-scale=1">' +
    '<title>vid2context transcript viewer</title>' +
    `<style>${safeCss}</style></head><body><div id="app"></div><script>${safeScript}</script></body></html>`;
  return [
    '// Generated by packages/mcp-apps/scripts/build-viewer.mjs from src/ui/. Do not edit by hand:',
    '// change src/ui/ and run `node packages/mcp-apps/scripts/build-viewer.mjs`.',
    '// biome-ignore format: generated bundle',
    '// biome-ignore lint/suspicious/noTemplateCurlyInString: the string is minified JavaScript, not a template',
    `export const VIEWER_HTML = ${JSON.stringify(html)};`,
    '',
  ].join('\n');
}

const isMain = process.argv[1] !== undefined && resolve(process.argv[1]) === join(here, 'build-viewer.mjs');
if (isMain) {
  const source = await buildViewerSource();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(outFile, 'utf8');
    } catch {
      current = '';
    }
    if (current !== source) {
      console.error('src/ui/viewer.html.ts is stale: run node packages/mcp-apps/scripts/build-viewer.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(outFile, source);
    console.error(`wrote ${outFile} (${source.length} bytes)`);
  }
}
