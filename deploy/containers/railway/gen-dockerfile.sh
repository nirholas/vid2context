#!/bin/sh
# Writes deploy/containers/railway/Dockerfile from deploy/containers/Dockerfile.
#
#   deploy/containers/railway/gen-dockerfile.sh          regenerate
#   deploy/containers/railway/gen-dockerfile.sh --check  exit 1 if it is stale
#
# Railway refuses to build any Dockerfile that contains a VOLUME instruction
# and mounts its volumes owned by root. So the Railway copy drops the VOLUME
# line and starts through railway/entrypoint.sh, which hands /data to the node
# user and then drops root. Everything else is identical to the main image.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
src="$here/../Dockerfile"
dest="$here/Dockerfile"

generate() {
  cat <<'HEADER'
# Generated by deploy/containers/railway/gen-dockerfile.sh from
# deploy/containers/Dockerfile. Do not edit: change the main Dockerfile and
# rerun the script. Railway rejects VOLUME, so attach a Railway volume at /data.
#
HEADER
  grep -v '^VOLUME ' "$src"
  cat <<'TAIL'

# ---------------------------------------------------------------- Railway
# Start as root only long enough to give the root-owned Railway volume at
# /data to the node user; entrypoint.sh then drops root with setpriv.
USER root
COPY deploy/containers/railway/entrypoint.sh /usr/local/bin/vid2context-entrypoint
ENTRYPOINT ["/usr/bin/tini", "-g", "--", "/usr/local/bin/vid2context-entrypoint"]
CMD ["node", "--import", "tsx", "packages/server/src/node.ts"]
TAIL
}

if [ "${1:-}" = "--check" ]; then
  generate | cmp -s - "$dest"
else
  generate > "$dest"
  echo "wrote $dest" >&2
fi
